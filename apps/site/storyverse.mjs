//   design/2026-11-05-gpom-meeting/lookdev/index.html   (artifact https://claude.ai/artifact/G4Pm2tMnkxBQeKcdSpid9j)
// whose look is locked. derive() keeps that page's scene code (the commit graph, the CRT filter, the words drawn
// into the frame, Maddie's clip list and the default timing) and drops the editor: the timeline, the sliders,
