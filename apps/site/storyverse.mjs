export const OUT_DIR = join(here, 'public', 'storyverse', 'hologram');

// section headers in the source module ("/* ---------- name ---------- */"): kept, or dropped (editor UI)
const KEEP = ['the bench: every knob', 'the timeline:', 'renderer and post', 'materials', 'the world', 'tags:', 'the shot at time t'];
const DROP = ['the edit:', 'the bench UI', 'playback'];
// the editor's saved settings and edits live in the browser; the public page always plays the default (locked) layout
const STRIP = [
  "try{Object.assign(P,JSON.parse(localStorage.getItem('gpom-holo-r5')||'{}'))}catch(e){}",
  "try{const l=JSON.parse(localStorage.getItem('gpom-holo-edit-1k2')||'null'); if(l) mergeEdit(l)}catch(e){}",
  "const save=()=>{try{localStorage.setItem('gpom-holo-r5',JSON.stringify(P))}catch(e){}};",
];

function must(cond, what) { if (!cond) throw new Error(`storyverse: the source page changed (${what}); re-check apps/site/storyverse.mjs`); }

export function derive(src = readFileSync(SOURCE, 'utf8')) {
  const importmap = src.match(/<script type="importmap">[\s\S]*?<\/script>/);
  must(importmap, 'no importmap');
  const mod = src.match(/<script type="module">([\s\S]*?)<\/script>/);
  must(mod, 'no module script');
  const parts = mod[1].split(/^\/\* ---------- (.+?) ---------- \*\/$/m);
  let code = parts[0], playback = '';
  for (let i = 1; i < parts.length; i += 2) {
    const name = parts[i], body = parts[i + 1];
    if (KEEP.some(k => name.startsWith(k))) code += `/* ---------- ${name} ---------- */${body}`;
    else if (DROP.some(k => name.startsWith(k))) { if (name.startsWith('playback')) playback = body; }
    else must(false, `unknown section "${name}"`);
  }
  for (const k of KEEP) must(code.includes(`/* ---------- ${k}`), `missing section "${k}"`);
  for (const s of STRIP) { must(code.split(s).length === 2, `expected once: ${s.slice(0, 50)}`); code = code.replace(s, ''); }
  // Maddie's voice is scheduled by the source's own functions, copied word for word
  const stopAudio = playback.match(/^function stopAudio\(\)\{.*$/m);
  const startAudio = playback.match(/^function startAudio\(\)\{[\s\S]*?SRC\.push\(src\)\}\}$/m);
  must(stopAudio && startAudio, 'stopAudio/startAudio not found in playback');
  const clips = [...code.matchAll(/"file": "(voice\/c\d+\.mp3)"/g)].map(m => m[1]);
  must(clips.length > 0, 'no voice clips in CLIPS0');
  const html = PAGE
    .replace('/*IMPORTMAP*/', () => importmap[0])
    .replace('/*SCENE*/', () => code.trim())
    .replace('/*AUDIO*/', () => stopAudio[0] + '\n' + startAudio[0]);
  return { html, clips };
}

// Writes the page if it changed. Returns 'written', 'same', or throws.
export function writeHologram() {
  const { html } = derive();
  const file = join(OUT_DIR, 'index.html');
  if (existsSync(file) && readFileSync(file, 'utf8') === html) return 'same';
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(file, html);
  return 'written';
}

